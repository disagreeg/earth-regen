  function fitCfg() {
    const c = (window.GG && GG.config && GG.config.ui && GG.config.ui.iconFit) || null;
    return (c && c.enabled === false) ? null : (c || { target: 18, min: 0.85, max: 1.25 });
  }
  

  function fitOf(name) {
    const cfg = fitCfg();
    if (!cfg) return null;
    const b = INK[name];
    if (!b) return null;                       
    const ext = Math.max(b[2], b[3]);
    if (!ext) return null;
    let f = (cfg.target || 18) / ext;
    f = Math.max(cfg.min || 0.85, Math.min(cfg.max || 1.25, f));
    return { f: f, cx: b[0] + b[2] / 2, cy: b[1] + b[3] / 2 };
  }

  function drawIcon(ctx, name, cx, cy, size, color, weight) {
    const list = paths(name);
    if (!list.length) return;
    const s = size / 24;
    const fit = fitOf(name);
    ctx.save();
    ctx.translate(cx - size / 2, cy - size / 2);
    ctx.scale(s, s);
    if (fit) {                       
      ctx.translate(12, 12);
      ctx.scale(fit.f, fit.f);
      ctx.translate(-fit.cx, -fit.cy);
    }
    ctx.strokeStyle = color;
    

    ctx.lineWidth = (weight || 1.8) / (fit ? fit.f : 1);
    ctx.lineCap = 'round';
    ctx.lineJoin = 'round';
    list.forEach(p => ctx.stroke(p));
    ctx.restore();
  }

  
  function svg(name, size, color, weight) {
    const fit = fitOf(name);
    let d = (P[name] || []).map(p => '<path d="' + p + '"/>').join('');
    if (fit) {
      d = '<g transform="translate(12 12) scale(' + fit.f.toFixed(4) + ') translate(' +
          (-fit.cx).toFixed(3) + ' ' + (-fit.cy).toFixed(3) + ')">' + d + '</g>';
    }
    return '<svg class="ic" width="' + (size || 20) + '" height="' + (size || 20) +
      '" viewBox="0 0 24 24" fill="none" stroke="' + (color || 'currentColor') +
      '" stroke-width="' + ((weight || 1.8) / (fit ? fit.f : 1)).toFixed(3) +
      '" stroke-linecap="round" stroke-linejoin="round">' + d + '</svg>';
  }

  return { drawIcon: drawIcon, svg: svg, has: n => !!P[n], paths: P, fitOf: fitOf, ink: INK };
